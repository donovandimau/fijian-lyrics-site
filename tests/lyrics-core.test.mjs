import assert from 'node:assert/strict';
import {parseLyrics,validateCues,secondsLabel,toLrc,toVtt,parseTime} from '../lyrics-core.js';
const lrc=parseLyrics('[offset:500]\n[00:01.00][00:05.00]Bula vinaka\n[00:09.25]Ni sa moce',NaN);
assert.equal(lrc.openEnded,true);
assert.deepEqual(lrc.cues.map(c=>c.start),[1.5,5.5,9.75]);
assert.equal(lrc.cues[0].end,5.5);
assert.equal(validateCues(lrc.cues),'');
const srt=parseLyrics('1\n00:00:01,000 --> 00:00:03,250\nBula\nvinaka\n\n2\n00:00:04,000 --> 00:00:06,000\nMoce',10);
assert.equal(srt.cues[0].text,'Bula\nvinaka');
assert.equal(srt.cues[0].end,3.25);
assert.equal(srt.cues[1].start,4);
assert.equal(validateCues(srt.cues,10),'');
const plain=parseLyrics('Bula vinaka\n\nNi sa moce',6);
assert.equal(plain.timed,false);assert.equal(plain.cues.length,2);assert.equal(plain.cues[1].end,6);
assert.equal(secondsLabel(59.999),'1:00.00');
assert.equal(parseLyrics(toLrc([{start:59.999,end:64,text:'Bula'}]),70).cues[0].start,60);
assert.match(toVtt(srt.cues),/00:00:01\.000 --> 00:00:03\.250/);
assert.match(validateCues([{start:0,end:3,text:'A'},{start:2,end:4,text:'B'}],6),/overlaps/);
assert.match(validateCues([{start:0,end:7,text:'A'}],6),/after/);
assert.ok(Number.isNaN(parseTime('bad')));
console.log('PASS: repeated LRC tags/offset, pre-audio import, SRT multiline/gaps, plain draft, timestamp carry/round-trip, VTT, overlap and duration validation.');
